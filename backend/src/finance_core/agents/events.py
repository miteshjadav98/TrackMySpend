"""Chat turn contract: the request, the streamed events, and the final result.

Streamed over SSE as `event: <type>` / `data: <json>`. The same models are published in
OpenAPI so the frontend's TypeScript types are generated, not hand-written.
"""

from __future__ import annotations

import uuid
from typing import Annotated, Literal

from pydantic import Field

from finance_core.conversations.schemas import MessageView
from finance_core.interactions import Interaction, PendingInteraction, TurnInput
from finance_core.schemas import ApiInput, ApiModel


class SendMessageRequest(ApiInput):
    # Generated by the client once per logical message and reused on retries, so a
    # network retry never runs the same turn twice.
    client_message_id: uuid.UUID
    input: TurnInput


class TurnResult(ApiModel):
    user_message: MessageView
    assistant_message: MessageView | None
    pending_interaction: PendingInteraction | None = None
    replayed: bool = False


class TurnStartedEvent(ApiModel):
    type: Literal["turn.started"] = "turn.started"
    user_message: MessageView


class StatusEvent(ApiModel):
    type: Literal["status"] = "status"
    stage: str
    label: str


class TextDeltaEvent(ApiModel):
    type: Literal["text.delta"] = "text.delta"
    delta: str


class InteractionEvent(ApiModel):
    type: Literal["interaction"] = "interaction"
    interaction: Interaction


class TurnCompletedEvent(ApiModel):
    type: Literal["turn.completed"] = "turn.completed"
    result: TurnResult


class TurnErrorEvent(ApiModel):
    type: Literal["error"] = "error"
    code: str
    message: str
    retryable: bool
    request_id: str | None = None


TurnEvent = Annotated[
    TurnStartedEvent
    | StatusEvent
    | TextDeltaEvent
    | InteractionEvent
    | TurnCompletedEvent
    | TurnErrorEvent,
    Field(discriminator="type"),
]
