import {
  ArrowDownLeft,
  ArrowUpRight,
  Briefcase,
  Calendar,
  Car,
  ChartPie,
  CircleEllipsis,
  CircleHelp,
  CirclePlus,
  Clapperboard,
  Gift,
  GraduationCap,
  HeartPulse,
  House,
  KeyRound,
  Landmark,
  Laptop,
  List,
  type LucideIcon,
  Plane,
  Plus,
  Receipt,
  Repeat,
  Shield,
  ShoppingBag,
  ShoppingBasket,
  Sparkles,
  Tag,
  TrendingUp,
  Undo2,
  Utensils,
} from "lucide-react";

// The API sends icon *names* (data), never markup; only names in this map render.
const ICONS: Record<string, LucideIcon> = {
  utensils: Utensils,
  "shopping-basket": ShoppingBasket,
  car: Car,
  "shopping-bag": ShoppingBag,
  home: House,
  receipt: Receipt,
  repeat: Repeat,
  clapperboard: Clapperboard,
  "heart-pulse": HeartPulse,
  "graduation-cap": GraduationCap,
  plane: Plane,
  sparkles: Sparkles,
  gift: Gift,
  shield: Shield,
  landmark: Landmark,
  "circle-ellipsis": CircleEllipsis,
  briefcase: Briefcase,
  laptop: Laptop,
  "trending-up": TrendingUp,
  "undo-2": Undo2,
  key: KeyRound,
  "circle-plus": CirclePlus,
  "circle-help": CircleHelp,
  tag: Tag,
  plus: Plus,
  "arrow-down-left": ArrowDownLeft,
  "arrow-up-right": ArrowUpRight,
  "pie-chart": ChartPie,
  list: List,
  calendar: Calendar,
};

export function NamedIcon({ name, className = "size-4" }: { name?: string | null; className?: string }) {
  const Icon = (name && ICONS[name]) || Tag;
  return <Icon aria-hidden className={className} />;
}
